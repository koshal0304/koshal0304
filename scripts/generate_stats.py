#!/usr/bin/env python3
"""
Neural-Dark GitHub stats card — generated by GitHub Actions, no third-party services.

Usage (in CI):   GITHUB_TOKEN=... GH_USER=koshal0304 python scripts/generate_stats.py
Local preview:   python scripts/generate_stats.py --mock sample.json
Placeholder:     python scripts/generate_stats.py --placeholder

Env:
  GH_USER          GitHub login (defaults to the repository owner)
  EXCLUDE_LANGS    comma-separated languages to ignore, e.g. "HTML,CSS"
  OUT              output path (default assets/generated/stats.svg)
"""
import datetime as dt
import html
import json
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.environ.get("OUT", os.path.join(ROOT, "assets", "generated", "stats.svg"))
USER = os.environ.get("GH_USER") or os.environ.get("GITHUB_REPOSITORY_OWNER") or "koshal0304"
EXCLUDE = {s.strip().lower() for s in os.environ.get("EXCLUDE_LANGS", "").split(",") if s.strip()}

C = dict(bg="#080C1A", card="#0C1224", line="#1C2541", line2="#26325A", text="#E6EDF7", muted="#9AA8C2", dim="#5B6782",
         cyan="#22D3EE", violet="#8B5CF6", purple="#A78BFA", pink="#E879F9", mint="#34D399", amber="#FBBF24")
SG = "SG,'Space Grotesk','Segoe UI',Ubuntu,Arial,sans-serif"
JB = "JB,SYM,'JetBrains Mono',Consolas,monospace"

QUERY = """
query($login: String!) {
  user(login: $login) {
    login
    followers { totalCount }
    repositories(first: 100, ownerAffiliations: OWNER, isFork: false, privacy: PUBLIC,
                 orderBy: {field: STARGAZERS, direction: DESC}) {
      totalCount
      nodes {
        stargazerCount
        languages(first: 10, orderBy: {field: SIZE, direction: DESC}) {
          edges { size node { name color } }
        }
      }
    }
    contributionsCollection {
      totalCommitContributions
      totalPullRequestContributions
      totalIssueContributions
      totalPullRequestReviewContributions
      restrictedContributionsCount
      contributionCalendar {
        totalContributions
        weeks { contributionDays { contributionCount date } }
      }
    }
  }
}"""


def fetch():
    token = os.environ.get("GITHUB_TOKEN")
    if not token:
        sys.exit("GITHUB_TOKEN is not set")
    req = urllib.request.Request(
        "https://api.github.com/graphql",
        data=json.dumps({"query": QUERY, "variables": {"login": USER}}).encode(),
        headers={"Authorization": f"bearer {token}", "Content-Type": "application/json", "User-Agent": "profile-stats"},
    )
    with urllib.request.urlopen(req, timeout=60) as r:
        data = json.load(r)
    if data.get("errors"):
        sys.exit(f"GraphQL error: {data['errors']}")
    return data["data"]["user"]


def compute(u):
    cc = u["contributionsCollection"]
    cal = cc["contributionCalendar"]
    days = [d for w in cal["weeks"] for d in w["contributionDays"]]
    days.sort(key=lambda d: d["date"])
    today = dt.date.today().isoformat()
    days = [d for d in days if d["date"] <= today]
    # streaks
    longest = run = 0
    for d in days:
        run = run + 1 if d["contributionCount"] > 0 else 0
        longest = max(longest, run)
    cur, i = 0, len(days) - 1
    if i >= 0 and days[i]["contributionCount"] == 0:
        i -= 1  # today not counted yet -> streak still alive
    while i >= 0 and days[i]["contributionCount"] > 0:
        cur += 1; i -= 1
    weeks = [sum(d["contributionCount"] for d in w["contributionDays"]) for w in cal["weeks"]][-52:]
    langs = {}
    for repo in u["repositories"]["nodes"]:
        for e in repo["languages"]["edges"]:
            n = e["node"]["name"]
            if n.lower() in EXCLUDE:
                continue
            col = e["node"]["color"] or "#8B949E"
            langs.setdefault(n, [0, col])[0] += e["size"]
    tot = sum(v[0] for v in langs.values()) or 1
    top = sorted(langs.items(), key=lambda kv: -kv[1][0])[:6]
    top = [(n, v[0] / tot, v[1]) for n, v in top]
    stars = sum(r["stargazerCount"] for r in u["repositories"]["nodes"])
    tiles = [
        (cal["totalContributions"], "contributions · 12 mo", C["cyan"]),
        (cc["totalCommitContributions"] + cc["restrictedContributionsCount"], "commits", C["purple"]),
        (cur, "current streak · days", C["mint"]),
        (longest, "longest streak · days", C["pink"]),
        (cc["totalPullRequestContributions"], "pull requests", C["amber"]),
        (stars, "stars earned", C["amber"]),
        (u["repositories"]["totalCount"], "public repos", C["cyan"]),
        (cc["totalPullRequestReviewContributions"], "code reviews", C["purple"]),
        (cc["totalIssueContributions"], "issues", C["pink"]),
    ]
    chosen = [t for t in tiles if t[0] > 0][:6]
    for t in tiles:
        if len(chosen) >= 6:
            break
        if t not in chosen:
            chosen.append(t)
    return dict(tiles=chosen, langs=top, weeks=weeks)


def e(s):
    return html.escape(str(s), quote=True)


def text(x, y, s, size, fam, wt, fill, anchor="start", extra=""):
    ff = SG if fam == "SG" else JB
    return (f'<text x="{x:.1f}" y="{y:.1f}" font-family="{ff}" font-size="{size}" font-weight="{wt}" fill="{fill}" '
            f'text-anchor="{anchor}" xml:space="preserve" {extra}>{e(s)}</text>')


def fmt(n):
    return f"{n/1000:.1f}k" if n >= 10000 else f"{n:,}"


def render(stats=None, placeholder=False):
    W, H = 1000, 320
    fonts = open(os.path.join(HERE, "fonts.css"), encoding="utf-8").read()
    css = (fonts + ".up{animation:up .8s cubic-bezier(.2,.8,.2,1) both}@keyframes up{from{opacity:0;transform:translateY(12px)}to{opacity:1;transform:none}}"
           "@media (prefers-reduced-motion: reduce){*{animation:none!important}}")
    defs = (f'<linearGradient id="fg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{C["cyan"]}"/><stop offset=".5" stop-color="{C["violet"]}" stop-opacity=".35"/>'
            f'<stop offset="1" stop-color="{C["pink"]}"/><animateTransform attributeName="gradientTransform" type="rotate" values="0 .5 .5;360 .5 .5" dur="12s" repeatCount="indefinite"/></linearGradient>'
            f'<pattern id="dots" width="22" height="22" patternUnits="userSpaceOnUse"><circle cx="1" cy="1" r="1" fill="{C["line2"]}" opacity=".5"/></pattern>'
            f'<linearGradient id="wk" x1="0" y1="1" x2="0" y2="0"><stop offset="0" stop-color="{C["violet"]}"/><stop offset="1" stop-color="{C["cyan"]}"/></linearGradient>')
    b = [f'<rect x=".7" y=".7" width="{W-1.4}" height="{H-1.4}" rx="18" fill="{C["bg"]}"/>',
         f'<rect x=".7" y=".7" width="{W-1.4}" height="{H-1.4}" rx="18" fill="url(#dots)"/>',
         f'<rect x=".7" y=".7" width="{W-1.4}" height="{H-1.4}" rx="18" fill="none" stroke="url(#fg)" stroke-width="1.3"/>',
         text(26, 38, "GITHUB TELEMETRY", 11, "JB", 700, C["cyan"], extra='letter-spacing="2"'),
         text(190, 38, f"@{USER} · last 12 months", 12, "SG", 500, C["muted"])]
    if placeholder:
        b.append(text(W / 2, 160, "Live stats sync on first workflow run", 24, "SG", 700, C["text"], "middle"))
        b.append(text(W / 2, 192, "Actions → Profile visuals → Run workflow   (refreshes automatically twice a day)", 13, "JB", 400, C["muted"], "middle"))
        b.append(f'<circle cx="{W/2}" cy="240" r="6" fill="{C["mint"]}"><animate attributeName="opacity" values="1;.2;1" dur="1.6s" repeatCount="indefinite"/></circle>')
    else:
        b.append(text(W - 26, 38, f"updated {dt.date.today().isoformat()} · built by GitHub Actions", 10.5, "JB", 400, C["dim"], "end"))
        tw, th, gx, gy, x0, y0 = 182, 86, 12, 12, 24, 58
        for k, (val, lab, col) in enumerate(stats["tiles"]):
            r, c = divmod(k, 3)
            x, y = x0 + c * (tw + gx), y0 + r * (th + gy)
            b.append(f'<g class="up" style="animation-delay:{k*0.08:.2f}s">'
                     f'<rect x="{x}" y="{y}" width="{tw}" height="{th}" rx="12" fill="{C["card"]}" stroke="{col}" stroke-opacity=".35"/>'
                     f'<rect x="{x+14}" y="{y}" width="28" height="2.5" rx="1.2" fill="{col}"/>'
                     + text(x + 14, y + 46, fmt(val), 32, "SG", 700, C["text"]) + text(x + 14, y + 68, lab.upper(), 9.5, "JB", 700, col, extra='letter-spacing="0.8"') + "</g>")
        # languages
        lx, lw = 624, 352
        b.append(text(lx, 72, "TOP LANGUAGES · BY BYTES", 10.5, "JB", 700, C["purple"], extra='letter-spacing="1.4"'))
        cx = lx
        for k, (n, frac, col) in enumerate(stats["langs"]):
            w = max(lw * frac - 2, 2)
            b.append(f'<rect x="{cx:.1f}" y="84" width="0" height="12" rx="3" fill="{col}"><animate attributeName="width" from="0" to="{w:.1f}" begin="{0.3+k*0.12:.2f}s" dur=".7s" fill="freeze"/></rect>')
            cx += lw * frac
        for k, (n, frac, col) in enumerate(stats["langs"]):
            r, c = divmod(k, 2)
            x, y = lx + c * 180, 128 + r * 34
            b.append(f'<g class="up" style="animation-delay:{0.4+k*0.08:.2f}s"><circle cx="{x+6}" cy="{y-4}" r="5" fill="{col}"/>'
                     + text(x + 18, y, {"Jupyter Notebook": "Jupyter"}.get(n, n)[:16], 13.5, "SG", 500, C["text"]) + text(x + 168, y, f"{frac*100:.1f}%", 11, "JB", 700, C["muted"], "end") + "</g>")
        if not stats["langs"]:
            b.append(text(lx, 130, "no public code yet", 13, "SG", 500, C["muted"]))
        # weekly contributions
        wks = stats["weeks"] or [0]
        mx = max(wks) or 1
        bx, by, bh, bw = 24, 300, 34, (W - 48) / max(len(wks), 1)
        b.append(text(24, 266, "WEEKLY CONTRIBUTIONS · 52 WEEKS", 9.5, "JB", 700, C["dim"], extra='letter-spacing="1.2"'))
        b.append(text(W - 26, 266, f"peak week: {max(wks)}", 9.5, "JB", 700, C["dim"], "end"))
        for k, v in enumerate(wks):
            h = 2 + (bh - 2) * v / mx
            b.append(f'<rect x="{bx+k*bw+1:.1f}" y="{by}" width="{bw-2.5:.1f}" height="0" rx="1.5" fill="url(#wk)" opacity="{0.35 + 0.65 * v / mx:.2f}">'
                     f'<animate attributeName="height" from="0" to="{h:.1f}" begin="{0.5+k*0.015:.2f}s" dur=".5s" fill="freeze"/>'
                     f'<animate attributeName="y" from="{by}" to="{by-h:.1f}" begin="{0.5+k*0.015:.2f}s" dur=".5s" fill="freeze"/></rect>')
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-labelledby="t">'
           f'<title id="t">GitHub stats for {e(USER)}</title><style>{css}</style><defs>{defs}</defs>{"".join(b)}</svg>')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(svg)
    print(f"wrote {OUT} ({len(svg)//1024} KB)")


if __name__ == "__main__":
    if "--placeholder" in sys.argv:
        render(placeholder=True)
    elif "--mock" in sys.argv:
        render(compute(json.load(open(sys.argv[sys.argv.index("--mock") + 1]))))
    else:
        render(compute(fetch()))
